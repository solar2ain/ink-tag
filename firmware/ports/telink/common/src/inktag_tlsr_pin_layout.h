#ifndef INKTAG_TLSR_PIN_LAYOUT_H
#define INKTAG_TLSR_PIN_LAYOUT_H
/* Sole vendor record-size/offset authority; these are non-executable data.
 * Shared BLE block remains 16B and GET/ACK remains 36B. */
#define INKTAG_TLSR_PIN_RECORD_BYTES 32u
#define INKTAG_TLSR_PIN_FACTORY_ADDRESS 0x7F110u
#define INKTAG_TLSR_AUX_FACTORY_ADDRESS 0x7F130u
#define INKTAG_TLSR_AUX_FACTORY_BYTES 16u
#define INKTAG_TLSR_SCREEN_FACTORY_ADDRESS 0x7F140u
#define INKTAG_TLSR_SCREEN_FACTORY_BYTES 32u
#if INKTAG_TLSR_PIN_FACTORY_ADDRESS + INKTAG_TLSR_PIN_RECORD_BYTES != INKTAG_TLSR_AUX_FACTORY_ADDRESS || \
    INKTAG_TLSR_AUX_FACTORY_ADDRESS + INKTAG_TLSR_AUX_FACTORY_BYTES != INKTAG_TLSR_SCREEN_FACTORY_ADDRESS || \
    INKTAG_TLSR_SCREEN_FACTORY_ADDRESS + INKTAG_TLSR_SCREEN_FACTORY_BYTES != 0x7F160u
#error Invalid TLSR Factory aux/default ownership boundary
#endif
#define INKTAG_TLSR_PIN_SETTINGS_VERSION 1u
#define INKTAG_TLSR_PIN_SETTINGS_BASE_BYTES 39u
#define INKTAG_TLSR_PIN_SETTINGS_PRESENCE_OFFSET 39u
#define INKTAG_TLSR_PIN_SETTINGS_BLOCK_OFFSET 40u
#define INKTAG_TLSR_AUX_SETTINGS_EXTRA_OFFSET 56u
#define INKTAG_TLSR_PIN_SETTINGS_RESERVED_OFFSET 60u
#define INKTAG_TLSR_PIN_SETTINGS_RESERVED_BYTES 4u
#define INKTAG_TLSR_PIN_SETTINGS_BYTES 64u
#if INKTAG_TLSR_PIN_SETTINGS_PRESENCE_OFFSET + 1u != INKTAG_TLSR_PIN_SETTINGS_BLOCK_OFFSET || \
    INKTAG_TLSR_PIN_SETTINGS_BLOCK_OFFSET + 16u != INKTAG_TLSR_AUX_SETTINGS_EXTRA_OFFSET || \
    INKTAG_TLSR_AUX_SETTINGS_EXTRA_OFFSET + 4u != INKTAG_TLSR_PIN_SETTINGS_RESERVED_OFFSET || \
    INKTAG_TLSR_PIN_SETTINGS_RESERVED_OFFSET + INKTAG_TLSR_PIN_SETTINGS_RESERVED_BYTES != INKTAG_TLSR_PIN_SETTINGS_BYTES
#error Invalid TLSR pin Settings envelope
#endif
#endif
