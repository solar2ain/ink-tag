static void inktag_tlsr_gpio_mux_compact(GPIO_PinTypeDef pin,GPIO_FuncTypeDef func) {
    uint8_t bit=(uint8_t)pin,mode=0u,shift=0u,mask=255u;
    unsigned bank=(unsigned)pin>>8u;
    if(pin==GPIO_PA5 || pin==GPIO_PA6) gpio_set_input_en(pin,1);
    else if(bank<4u && bit && !(bit&(uint8_t)(bit-1u))) {
        uint8_t index=0u;
        while((bit>>index)!=1u) ++index;
        shift=(uint8_t)((index&3u)*2u);
        mask=(uint8_t)~(3u<<shift);
        if((unsigned)func<32u)
            mode=(uint8_t)((s_gpio_mux_codes[bank*8u+index][(unsigned)func>>2u] >>
                           (((unsigned)func&3u)*2u))&3u);
    }
    unsigned reg=0x5a8u+(bank<<1u)+((pin&0xf0u)?1u:0u);
    write_reg8(reg,(uint8_t)((read_reg8(reg)&mask)|(mode<<shift)));
}
static void inktag_tlsr_gpio_func_compact(GPIO_PinTypeDef pin,GPIO_FuncTypeDef func) {
    uint8_t bit=(uint8_t)pin;
    if(func==AS_GPIO) { BM_SET(reg_gpio_func(pin),bit); return; }
    BM_CLR(reg_gpio_func(pin),bit);
    if(func>AS_GPIO) inktag_tlsr_gpio_mux_compact(pin,func);
}
static void inktag_tlsr_gpio_func2_compact(GPIO_PinTypeDef pin,GPIO_FuncTypeDef func) {
    uint8_t bit=(uint8_t)pin;
    if(func==AS_GPIO) { BM_SET(reg_gpio_func(pin),bit); return; }
    inktag_tlsr_gpio_mux_compact(pin,func);
    BM_CLR(reg_gpio_func(pin),bit);
}
