"""Compile only the host GUI adapter. Never builds or changes MCU firmware."""
import argparse,base64,hashlib,json,subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
GUI=ROOT/'firmware/common/gui'
ASSETS=ROOT/'cli/src/inktag_cli/_assets'
DEFINES=['INKTAG_GUI_HOST_PREVIEW','INKTAG_GUI_NATIVE_FONT_ASSETS','INKTAG_GUI_ROLE_FONT_ASSETS',
 'INKTAG_GUI_ATOMIC_FONT_ASSETS','INKTAG_GUI_ASSET_READ_FAILURE_AWARE',
 'INKTAG_GUI_EMBEDDED_FONT_FALLBACK','INKTAG_GUI_RAW_VIEWPORT','INKTAG_GUI_FACTORY_FONT_LAYOUT']
SOURCES=['tools/emulator/native-font-preview.c']+['firmware/common/gui/'+s for s in
 ('Adafruit_GFX.c','u8g2_font.c','inktag_gui_fonts.c','inktag_gui.c','inktag_calendar.c','inktag_gui_asset_package.c')]+['firmware/common/protocol/inktag_protocol_core.c']
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def inputs():
 headers=[p for name in ('gui','epd','ble','protocol','power') for p in (ROOT/'firmware/common'/name).glob('*.h')]
 return {p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes().replace(b'\r\n',b'\n')).hexdigest() for p in sorted(set([ROOT/p for p in SOURCES]+headers+list(GUI.glob('*.inc'))+list((ROOT/'tools/emulator').glob('inktag_gui_*_preview.inc'))))}
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--emcc',required=True);p.add_argument('--wsl',action='store_true');a=p.parse_args()
 before=inputs();build=ROOT/'.local/native-font-preview';build.mkdir(parents=True,exist_ok=True)
 wasm=build/'native-preview.wasm'
 path=wasm.relative_to(ROOT).as_posix()
 args=[a.emcc,*SOURCES,'-Ifirmware/common/gui','-Ifirmware/common/protocol','-Ifirmware/common/epd',
       *['-D'+n+'=1' for n in DEFINES],'-O2','--no-entry','-sSTANDALONE_WASM=1','-sFILESYSTEM=0',
       '-sINITIAL_MEMORY=16777216','-sSTACK_SIZE=1048576',
       '-sEXPORTED_FUNCTIONS=["_malloc","_free","_nf_config","_nf_string","_nf_package","_nf_region","_nf_render"]','-o',path]
 version=subprocess.check_output((['wsl','--exec'] if a.wsl else [])+[a.emcc,'--version'],text=True)
 subprocess.run((['wsl','--exec'] if a.wsl else [])+args,cwd=ROOT,check=True)
 assert inputs()==before,'GUI inputs changed during host compilation'
 target=ASSETS/'nativePreviewWasm.js'
 target.write_text('// Generated by tools/emulator/build-native-font-preview.py; shipping common GUI, not MCU firmware.\n'+'globalThis.InkTagNativePreviewWasm="'+base64.b64encode(wasm.read_bytes()).decode()+'";\n',encoding='utf-8',newline='\n')
 manifest=dict(compiler=version,command=args,inputTextNormalization='CRLF to LF, same as Git text checkout',inputs=before,wasmSha256=sha(wasm),assetSha256=sha(target))
 (ASSETS/'nativePreview.inputs.json').write_text(json.dumps(manifest,indent=2)+'\n',newline='\n')
 print(json.dumps(dict(wasmBytes=wasm.stat().st_size,wasmSha256=sha(wasm),asset=str(target)),indent=2))
if __name__=='__main__':main()
