import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const webuiRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourcePath = resolve(webuiRoot, '..', 'firmware', 'common', 'gui', 'inktag_gui_fonts.c')
const outputPath = resolve(webuiRoot, 'src', 'device-gui', 'fonts.generated.ts')
const source = await readFile(sourcePath, 'utf8')

const fontNames = {
  'wqy9-lunar': 'u8g2_font_wqy9_t_lunar',
  'wqy12-lunar': 'u8g2_font_wqy12_t_lunar',
  'helv-bold-14-num': 'u8g2_font_helvB14_tn',
  'helv-bold-18-num': 'u8g2_font_helvB18_tn',
}

const generated = {}
for (const [id, cName] of Object.entries(fontNames)) {
  const pattern = new RegExp('const\\s+uint8_t\\s+' + cName + '\\[(\\d+)\\][\\s\\S]*?=\\s*((?:"(?:\\\\.|[^"\\\\])*"\\s*)+);')
  const match = source.match(pattern)
  if (!match) throw new Error('Cannot find ' + cName + ' in ' + sourcePath)
  const payload = decodeCStringSequence(match[2])
  const expected = Number(match[1])
  if (payload.length + 1 !== expected) throw new Error(cName + ': decoded ' + payload.length + ' bytes plus NUL, expected ' + expected)
  const bytes = new Uint8Array(expected)
  bytes.set(payload)
  generated[id] = { base64: Buffer.from(bytes).toString('base64'), bytes: expected, cName }
}

const body = [
  '// Generated by tools/generate-device-fonts.mjs from firmware/common/gui/inktag_gui_fonts.c.',
  '// Do not edit this file by hand.',
  'export const deviceFontData = ' + JSON.stringify(generated, null, 2) + ' as const',
  '',
].join('\n')
await writeFile(outputPath, body, 'utf8')

function decodeCStringSequence(body) {
  const output = []
  for (const match of body.matchAll(/"((?:\\.|[^"\\])*)"/g)) {
    const text = match[1]
    for (let index = 0; index < text.length; index += 1) {
      const char = text[index]
      if (char !== '\\') {
        output.push(char.charCodeAt(0))
        continue
      }
      const next = text[++index]
      if (/[0-7]/.test(next)) {
        let octal = next
        while (octal.length < 3 && /[0-7]/.test(text[index + 1] || '')) octal += text[++index]
        output.push(Number.parseInt(octal, 8))
      } else if (next === 'x') {
        let hex = ''
        while (/[0-9a-f]/i.test(text[index + 1] || '')) hex += text[++index]
        output.push(Number.parseInt(hex, 16))
      } else {
        output.push({ n: 10, r: 13, t: 9, '0': 0, '\\': 92, '"': 34 }[next] ?? next.charCodeAt(0))
      }
    }
  }
  return Uint8Array.from(output)
}
