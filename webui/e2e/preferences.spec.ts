import { expect, test } from '@playwright/test'

test.use({ locale: 'zh-CN' })

for (const width of [1280, 390]) {
  test(`browser preferences persist with no Bluetooth at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 })
    await page.addInitScript(() => localStorage.setItem('inktag-getting-started-v1', 'seen'))
    await page.goto('/#/preferences')
    await expect(page.getByRole('heading', { name: '偏好设置', exact: true })).toBeVisible()
    await expect(page).toHaveURL(/\/device\?tab=preferences$/)
    await expect(page.getByRole('heading', { name: '设备设置', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: '客户端设置', exact: true })).toBeVisible()
    await expect(page.locator('.offline-ribbon')).toHaveCount(0)
    await expect(page.locator('.side-nav nav a').filter({ hasText: '设置' })).toHaveCount(1)
    await expect(page.locator('.side-nav nav a').filter({ hasText: '偏好设置' })).toHaveCount(0)
    await page.getByLabel('外观', { exact: true }).selectOption('dark')
    await expect(page.locator('html')).toHaveAttribute('data-resolved-theme', 'dark')
    await expect(page.getByLabel('界面动画', { exact: true })).toHaveCount(0)
    await expect(page.locator('.settings-group-title').first()).toHaveCSS('font-size', '14px')
    await page.getByLabel('语言', { exact: true }).selectOption('en')
    await expect(page.getByRole('heading', { name: 'Preferences', exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Language', { exact: true })).toHaveValue('en')
    await expect(page.getByLabel('Appearance', { exact: true })).toHaveValue('dark')
    await expect(page.locator('html')).not.toHaveAttribute('data-motion')
    const headings = await page.locator('.browser-preferences h2, .browser-preferences h3, .page-header h1').all()
    expect(headings.length).toBeGreaterThanOrEqual(4)
    for (const heading of headings) {
      const color = await heading.evaluate((node) => getComputedStyle(node).color)
      expect(Number(color.match(/\d+/)?.[0]), `dark heading foreground: ${color}`).toBeGreaterThan(160)
    }
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: test.info().outputPath(`preferences-${width}-dark.png`) })
    await expect(page.getByRole('button', { name: 'Open getting-started tutorial' })).toHaveCount(0)
    await page.goto('/#/device?tab=about')
    await expect(page.getByRole('link', { name: 'good-display.com' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Open tutorial', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Meet e-paper' })).toBeVisible()
    await expect(page.locator('.guide-facts')).toContainText('medical guarantee')
    await expect(page.getByRole('link', { name: 'About e-paper (Good Display)' })).toHaveCount(0)
    await expect(page.locator('.getting-started a')).toHaveCount(0)
    await page.screenshot({ path: test.info().outputPath(`tutorial-${width}-english.png`) })
    await page.keyboard.press('Escape')
    await page.goto('/#/device?tab=preferences')
    await page.getByLabel('Language', { exact: true }).selectOption('zh-CN')
    await expect(page.getByRole('heading', { name: '偏好设置', exact: true })).toBeVisible()
  })
}

test('default language follows browser; explicit theme ignores system change', async ({ browser }) => {
  const context = await browser.newContext({ baseURL: test.info().project.use.baseURL, locale: 'en-US', colorScheme: 'dark' })
  const page = await context.newPage()
  await page.goto('/#/preferences')
  await page.getByRole('button', { name: 'Skip for now' }).click()
  await expect(page.getByRole('heading', { name: 'Preferences', exact: true })).toBeVisible()
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('browser')
  await expect(page.locator('html')).toHaveAttribute('data-resolved-theme', 'dark')
  await page.getByLabel('Appearance', { exact: true }).selectOption('light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-resolved-theme', 'light')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const duration = () => page.evaluate(() => {
    const spinner = document.createElement('span'); spinner.className = 'spin'; document.body.append(spinner)
    const value = getComputedStyle(spinner).animationDuration; spinner.remove(); return value
  })
  expect(parseFloat(await duration())).toBeLessThan(.01)
  await expect(page.getByLabel('Interface animation', { exact: true })).toHaveCount(0)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  expect(await duration()).toBe('1.1s')
  await context.close()
})
