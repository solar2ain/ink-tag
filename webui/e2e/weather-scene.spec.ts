import { expect,test } from '@playwright/test'
import { readFile,copyFile } from 'node:fs/promises'
test.use({locale:'zh-CN'})
for(const width of [1440,390])test(`weather controls edit, preview, export and restore at ${width}px`,async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.addInitScript(()=>localStorage.setItem('inktag-getting-started-v1','seen'))
  await page.setViewportSize({width,height:900})
  await page.goto('/#/create/canvas/weather-paper?width=400&height=300')
  await expect(page.getByLabel('创作画板')).toBeVisible({timeout:15000})
  await expect(page.locator('.native-template-title')).toContainText('主机动态页面')
  await expect(page.getByRole('button',{name:'发送到设备',exact:true})).toBeDisabled()
  if(width<500){await page.getByRole('button',{name:'打开编辑面板',exact:true}).click();await page.getByRole('navigation',{name:'编辑面板',exact:true}).getByRole('button',{name:'属性',exact:true}).click()}
  await page.getByText('天气数据源与预览',{exact:true}).click()
  await page.getByLabel('天气地点名称',{exact:true}).fill('宁波')
  await page.getByRole('button',{name:'应用数据源',exact:true}).click()
  await expect(page.locator('.weather-source-panel [role=status]')).toContainText('数据源已保存')
  const exporting=page.waitForEvent('download');await page.getByRole('button',{name:'导出主机任务',exact:true}).click()
  const file=await exporting,doc=JSON.parse(await readFile(await file.path(),'utf8'))
  expect(doc).toMatchObject({version:1,pageMode:'host-dynamic',width:400,height:300,weatherSource:{label:'宁波'}})
  expect(doc.widgets.some((w:any)=>w.hostWeather?.field==='temperature-chart')).toBe(true)
  expect(JSON.stringify(doc)).not.toContain('expected_device_id')
  await copyFile(await file.path(),`../.local/weather-browser-export-${width}.inktag.json`)
  const png=page.waitForEvent('download');await page.getByRole('button',{name:'下载 PNG',exact:true}).click()
  expect((await readFile(await (await png).path())).length).toBeGreaterThan(600)
  await page.getByRole('button',{name:'设备效果预览',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'设备效果预览'}).getByRole('status')).toContainText('400 × 300')
  await page.screenshot({path:`../.local/weather-scene-${width}.png`})
  await page.getByRole('button',{name:'关闭设备效果预览',exact:true}).click()
  await page.getByRole('button',{name:'保存作品',exact:true}).click()
  await page.getByRole('dialog',{name:'保存作品'}).getByRole('button',{name:'保存页面',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'保存作品'})).toHaveCount(0)
  await page.goto('/#/library')
  await page.locator('.page-resource').getByRole('link',{name:'继续编辑'}).click()
  await expect(page.locator('footer [role=status]')).toContainText('已打开本地页面')
  if(width<500){await page.getByRole('button',{name:'打开编辑面板',exact:true}).click();await page.getByRole('navigation',{name:'编辑面板',exact:true}).getByRole('button',{name:'属性',exact:true}).click()}
  await page.getByText('天气数据源与预览',{exact:true}).click()
  await expect(page.getByLabel('天气地点名称',{exact:true})).toHaveValue('宁波')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
